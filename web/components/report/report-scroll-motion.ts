export function reportScrollEase(progress: number) {
  const index = Math.max(0, Math.min(1, progress)) * (samples.length - 1);
  const start = Math.floor(index);
  const end = Math.min(start + 1, samples.length - 1);
  return samples[start] + (samples[end] - samples[start]) * (index - start);
}
